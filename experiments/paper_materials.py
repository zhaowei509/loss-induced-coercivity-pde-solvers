def write_manifest(retained: list[dict[str, str]], generated: list[dict[str, str]],
                   tables: list[dict[str, str]]) -> None:
    files = []
    for path in sorted(OUT.rglob("*")):
        if path.is_file() and path.name != "manifest.json":
            files.append({
                "path": str(path.relative_to(ROOT)),
                "sha256": sha256(path),
                "bytes": path.stat().st_size,
            })
    manifest = {
        "schema_version": 1,
        "generated_on": "2026-09-21",
        "generator": "experiments/paper_materials.py",
        "policy": "read-only derivation from authoritative formal outputs",
        "retained_figures": retained,
        "generated_figures": generated,
        "tables": tables,
        "files": files,
    }
    (OUT / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")


