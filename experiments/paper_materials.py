def radial_records() -> list[dict[str, Any]]:
    root = ROOT / "output/experiment2/deep_ritz_radial_scan_formal_20260921_v1"
    rows = []
    for seed in range(10):
        rows.extend(read_json(root / f"seed_{seed:05d}.json")["records"])
    if len(rows) != 780:
        raise RuntimeError(f"Expected 780 radial records, found {len(rows)}.")
    return rows


def range_series(rows: list[dict[str, Any]], branch: str, sign: str,
                 field: str) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    selected = [row for row in rows if row["branch"] == branch and row["t"] != 0]
    if sign == "positive":
        selected = [row for row in selected if row["t"] > 0]
    elif sign == "negative":
        selected = [row for row in selected if row["t"] < 0]
    radii = sorted({float(row["abs_t"]) for row in selected})
    medians, lows, highs = [], [], []
    for radius in radii:
        values = []
        for row in selected:
            if float(row["abs_t"]) != radius:
                continue
            value: Any = row
            for part in field.split("."):
                value = value[part]
            values.append(float(value))
        summary = quantiles(values)
        medians.append(summary["median"])
        lows.append(summary["minimum"])
        highs.append(summary["maximum"])
    return (np.asarray(radii), np.asarray(medians), np.asarray(lows),
            np.asarray(highs))


def radial_panel(ax: Any, series: list[tuple[str, str, str]], *, title: str,
                 ylabel: str, yscale: str) -> None:
    rows = radial_records()
    for label, color, sign in series:
        branch = "p4" if "p=4" in title else "ac"
        field = ("quadrature_512.energy" if "energy" in ylabel.lower()
                 and "|t|^4" not in ylabel else "energy_over_abs_t_fourth_512")
        x, median, low, high = range_series(rows, branch, sign, field)
        ax.fill_between(x, low, high, color=color, alpha=0.13, linewidth=0)
        ax.plot(x, median, color=color, marker="o", markersize=3.2,
                linewidth=1.7, label=label)
    ax.set_xscale("log", base=2)
    ax.set_xticks((0.25, 0.5, 1, 2, 4, 8, 16, 32),
                  (".25", ".5", "1", "2", "4", "8", "16", "32"))
    if yscale == "symlog":
        normalized = "|t|^4" in ylabel
        ax.set_yscale("symlog", linthresh=1e-3 if normalized else 1.0)
        if normalized:
            ax.set_yticks((-100.0, -1.0, 0.0, 1.0, 100.0))
        else:
            ax.set_yticks((-100.0, -1.0, 0.0, 1.0, 100.0, 1e4))
    else:
        ax.set_yscale(yscale)
    ax.set_xlabel(r"Radius $|t|$")
    ax.set_ylabel(ylabel)
    ax.set_title(title, loc="left", fontweight="semibold", pad=7)
    ax.grid(axis="y", color=GRID, linewidth=0.5)
    ax.set_axisbelow(True)
    ax.tick_params(axis="both", which="major", length=3, width=0.7,
                   colors=INK, labelcolor=INK)
    ax.legend(frameon=False, loc="best")


