def read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def quantiles(values: Iterable[float]) -> dict[str, float]:
    array = np.asarray(list(values), dtype=float)
    if array.size == 0:
        raise ValueError("Cannot summarize an empty sequence.")
    return {
        "q1": float(np.quantile(array, 0.25)),
        "median": float(np.median(array)),
        "q3": float(np.quantile(array, 0.75)),
        "minimum": float(np.min(array)),
        "maximum": float(np.max(array)),
    }


def sci(value: float, digits: int = 2) -> str:
    if value == 0:
        return "$0$"
    mantissa, exponent = f"{value:.{digits}e}".split("e")
    return rf"${mantissa}\times10^{{{int(exponent)}}}$"


def num(value: float, digits: int = 4) -> str:
    return f"{value:.{digits}f}"


def latex_table(path: Path, columns: str, header: str, rows: list[str],
                caption: str, label: str, *, table_star: bool = True,
                tabcolsep: int = 4, font: str = r"\small") -> None:
    environment = "table*" if table_star else "table"
    body = "\n".join(rows)
    text = rf"""% Generated by experiments/paper_materials.py from authoritative formal outputs.
\begin{{{environment}}}[t]
\centering
{font}
\setlength{{\tabcolsep}}{{{tabcolsep}pt}}
\renewcommand{{\arraystretch}}{{1.12}}
\begin{{tabular}}{{{columns}}}
\hline
{header} \\
\hline
{body}
\hline
\end{{tabular}}
\caption{{{caption}}}
\label{{{label}}}
\end{{{environment}}}
"""
    path.write_text(text, encoding="utf-8")


def copy_retained_figures() -> list[dict[str, str]]:
    mapping = [
        (
            ROOT / "output/experiment1/formal_20260916_v2/derived/figure1_toy_convergence",
            FIGURES / "figure01_toy_convergence",
        ),
        (
            ROOT / "output/experiment1/formal_20260916_v2/derived/figure2_general_case",
            FIGURES / "figure02_general_confinement",
        ),
        (
            ROOT / "output/experiment2/formal_20260917_v1/derived_paper_20260917_v16/figure3_experiment2",
            FIGURES / "figure03_residual_and_ritz",
        ),
        (
            ROOT / "output/experiment4/formal_20260918_v1/figure4_local_unfreezing",
            FIGURES / "figure04_local_unfreezing",
        ),
    ]
    records = []
    for source_stem, destination_stem in mapping:
        for suffix in (".pdf", ".png"):
            source = source_stem.with_suffix(suffix)
            destination = destination_stem.with_suffix(suffix)
            if not source.is_file():
                raise FileNotFoundError(source)
            shutil.copy2(source, destination)
            if sha256(source) != sha256(destination):
                raise RuntimeError(f"Retained figure changed during copy: {source}")
        records.append({
            "source_pdf": str(source_stem.with_suffix(".pdf").relative_to(ROOT)),
            "bundle_pdf": str(destination_stem.with_suffix(".pdf").relative_to(ROOT)),
            "sha256": sha256(destination_stem.with_suffix(".pdf")),
            "status": "retained byte-for-byte",
        })
    return records


