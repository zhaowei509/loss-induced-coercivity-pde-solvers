def application_rows() -> tuple[dict[str, Any], list[dict[str, Any]],
                                list[dict[str, Any]], list[dict[str, Any]]]:
    scale_root = ROOT / "output/experiment2/application_scale_formal_20260921_v1"
    unfreeze_root = ROOT / "output/experiment4/application_scale_unfreezing_formal_20260921_v1"
    frequency_root = ROOT / "output/experiment2/target_frequency_formal_20260921_v1"
    summary = read_json(scale_root / "summary.json")
    central = []
    unfrozen = []
    frequency = []
    for seed in range(20, 30):
        base = read_json(scale_root / f"W128_C_seed_{seed}.json")
        if base.get("evaluation") is not None:
            central.append(base)
        row = read_json(unfreeze_root / f"seed_{seed}.json")
        if row.get("dynamics") is not None:
            unfrozen.append(row)
        target = read_json(frequency_root / f"W128_C_k2_seed_{seed}.json")
        if base.get("evaluation") is not None and target.get("evaluation") is not None:
            frequency.append({"seed": seed, "k1": base, "k2": target})
    if len(central) != 9 or len(unfrozen) != 9 or len(frequency) != 9:
        raise RuntimeError("Unexpected S3 finite-result count.")
    return summary, central, unfrozen, frequency


def errorbar_panel(ax: Any, labels: list[str], records: list[dict[str, Any] | None],
                   *, title: str, subtitle: str, color: str,
                   failure_note: str | None = None) -> None:
    x = np.arange(len(labels), dtype=float)
    for index, record in enumerate(records):
        if record is None:
            ax.axvspan(index - 0.34, index + 0.34, color=LIGHT, zorder=0)
            ax.text(index, 2.35e-5, "All 10 runs failed\nthe conditioning screen",
                    ha="center", va="center", fontsize=6.8, color=MUTED)
            ax.plot(index, 1.55e-5, marker="x", markersize=6, mew=1.2,
                    color=MUTED, clip_on=False)
            continue
        median = float(record["relative_l2_error_median"])
        q1 = float(record["relative_l2_error_q1"])
        q3 = float(record["relative_l2_error_q3"])
        ax.errorbar(index, median, yerr=[[median - q1], [q3 - median]],
                    fmt="o", markersize=5.2, color=color, ecolor=color,
                    elinewidth=1.3, capsize=3, markeredgecolor="white",
                    markeredgewidth=0.7, zorder=3)
        alignment = ("left" if index == 0 else
                     "right" if index == len(records) - 1 else "center")
        ax.text(index, q3 + 2.7e-6, f"{record['finite_count']}/10 finite",
                ha=alignment, va="bottom", fontsize=7.1, color=INK)
    ax.set_xticks(x, labels)
    ax.set_ylim(1.15e-5, 6.25e-5)
    ax.yaxis.set_major_formatter(FuncFormatter(lambda value, _: f"{value * 1e5:.0f}"))
    ax.set_ylabel(r"Relative $L^2$ error ($\times 10^{-5}$)")
    ax.set_title(title, loc="left", fontweight="semibold", pad=16)
    ax.text(0.0, 1.015, subtitle, transform=ax.transAxes, ha="left",
            va="bottom", fontsize=6.9, color=MUTED)
    ax.grid(axis="y", color=GRID, linewidth=0.55)
    ax.set_axisbelow(True)
    if failure_note:
        ax.text(0.02, 0.04, failure_note, transform=ax.transAxes, ha="left",
                va="bottom", fontsize=6.9, color=MUTED)


def paired_panel(ax: Any, pairs: list[tuple[float, float]], labels: tuple[str, str],
                 *, title: str, subtitle: str, color: str, annotation: str | None,
                 log_scale: bool) -> None:
    for before, after in pairs:
        ax.plot((0, 1), (before, after), color=color, alpha=0.28,
                linewidth=0.9, marker="o", markersize=2.5)
    medians = [float(np.median([pair[index] for pair in pairs])) for index in (0, 1)]
    ax.plot((0, 1), medians, color=color, linewidth=2.3, marker="o",
            markersize=5.3, markeredgecolor="white", markeredgewidth=0.7,
            zorder=4, label="median")
    ax.set_xticks((0, 1), labels)
    ax.set_xlim(-0.28, 1.28)
    if log_scale:
        ax.set_yscale("log")
        ax.set_ylabel(r"Relative $L^2$ error")
    else:
        ax.yaxis.set_major_formatter(FuncFormatter(lambda value, _: f"{value * 1e5:.1f}"))
        ax.set_ylabel(r"Relative $L^2$ error ($\times 10^{-5}$)")
    ax.set_title(title, loc="left", fontweight="semibold", pad=16)
    ax.text(0.0, 1.015, subtitle, transform=ax.transAxes, ha="left",
            va="bottom", fontsize=6.9, color=MUTED)
    ax.grid(axis="y", color=GRID, linewidth=0.55)
    ax.set_axisbelow(True)
    if annotation:
        ax.text(0.97, 0.95, annotation, transform=ax.transAxes, ha="right",
                va="top", fontsize=7.2, color=INK,
                bbox={"boxstyle": "round,pad=0.24", "facecolor": "white",
                      "edgecolor": LIGHT, "alpha": 0.95})


